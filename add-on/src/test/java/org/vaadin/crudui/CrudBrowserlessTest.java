	private static <C extends Component> void assertFieldType(Form<?> form, String label, Class<C> type) {
		Component field = form.getContent().getChildren()
				.filter(HasLabel.class::isInstance)
				.filter(component -> label.equals(((HasLabel) component).getLabel()))
				.findFirst()
				.orElseThrow();
		assertInstanceOf(type, field);
	}

	private static Button buttonAt(BrowserlessUIContext window, int index) {
		return window.find(Button.class).atIndex(index);
	}

