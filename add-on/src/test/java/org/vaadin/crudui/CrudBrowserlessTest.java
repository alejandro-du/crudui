	@Test
	void operationFieldsAndConvertersWorkForMethodAndPropertyBindings() {
		Person person = new Person("Ada", 37);
		var formFactory = AutoGeneratedFormFactory.of(Person.class)
				.fields(Field.of(Person::getName, Person::setName).caption("Name"))
				.fieldsFor(CrudOperation.CREATE,
						Field.of(Person::getAge, Person::setAge, Integer.class)
								.fieldType(TextField.class)
								.caption("Age")
								.converter(new StringToIntegerConverter("Enter a number")))
				.additionalFieldsFor(CrudOperation.CREATE,
						Field.of("nickname").fieldType(TextField.class).caption("Nickname"))
				.additionalFieldsFor(CrudOperation.READ,
						Field.of("age").fieldType(IntegerField.class).caption("Age"))
				.fieldsFor(CrudOperation.DELETE,
						Field.of("nickname").fieldType(TextField.class).caption("Nickname"));
		Form<Person> createForm = (Form<Person>) formFactory.build(person, CrudOperation.CREATE);

		try (BrowserlessApplicationContext app = BrowserlessApplicationContext
				.forComponent(() -> (com.vaadin.flow.component.Component) createForm)) {
			BrowserlessUIContext window = app.newUser().newWindow();
			assertTrue(window.find(TextField.class).withLabel("Age").exists());
			assertTrue(window.find(TextField.class).withLabel("Nickname").exists());
			assertFalse(window.find(TextField.class).withLabel("Name").exists());

			TextField ageField = window.find(TextField.class).withLabel("Age").single();
			window.test(ageField).setValue("42");
			assertEquals(42, person.getAge());
			assertTrue(createForm.isValid());

			window.test(ageField).setValue("not a number");
			assertFalse(createForm.isValid());

			Form<Person> updateForm = (Form<Person>) formFactory.build(person, CrudOperation.UPDATE);
			assertEquals(1, updateForm.getContent().getComponentCount());
			assertEquals("Ada", person.getName());

			Form<Person> readForm = (Form<Person>) formFactory.build(person, CrudOperation.READ);
			Form<Person> deleteForm = (Form<Person>) formFactory.build(person, CrudOperation.DELETE);
			assertEquals(2, readForm.getContent().getComponentCount());
			assertEquals(1, deleteForm.getContent().getComponentCount());
			assertEquals("Name", ((HasLabel) readForm.getContent().getComponentAt(0)).getLabel());
			assertEquals("Age", ((HasLabel) readForm.getContent().getComponentAt(1)).getLabel());
			assertEquals("Nickname", ((HasLabel) deleteForm.getContent().getComponentAt(0)).getLabel());
		}
	}

