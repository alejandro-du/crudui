	@Test
	void dialogLayoutUsesCustomGridAndSavesFromDialog() {
		Person ada = new Person("Ada", 37);
		List<Person> people = new ArrayList<>(List.of(ada));
		TreeGrid<Person> treeGrid = new TreeGrid<>();
		TreeData<Person> treeData = new TreeData<>();
		treeGrid.addHierarchyColumn(Person::getName).setHeader("Name");
		treeGrid.setTreeData(treeData);
		treeData.addItem(null, ada);
		Crud<Person> crud = Crud.of(Person.class)
				.list(GridList.of(Person.class).grid(treeGrid))
				.layout(DialogCrudLayout.of(Person.class)
						.dialogWidth("600px")
						.dialogModal(false)
						.dialogDraggable(false)
						.dialogResizable(false)
						.dialogCloseOnEsc(false)
						.dialogCloseOnOutsideClick(true))
				.onCreate(person -> {
					people.add(person);
					treeData.addItem(null, person);
				})
				.onUpdate(ignored -> { })
				.onDelete(person -> {
					people.remove(person);
					treeData.removeItem(person);
				})
				.build();

		try (BrowserlessApplicationContext app = BrowserlessApplicationContext.forComponent(() -> crud)) {
			BrowserlessUIContext window = app.newUser().newWindow();
			assertSame(treeGrid, window.find(TreeGrid.class).single());
			window.test(buttonAt(window, 1)).click();
			Dialog dialog = window.find(Dialog.class).single();
			assertTrue(dialog.isOpened());
			assertEquals("600px", dialog.getWidth());
			assertEquals(ModalityMode.MODELESS, dialog.getModality());
			assertFalse(dialog.isDraggable());
			assertFalse(dialog.isResizable());
			assertFalse(dialog.isCloseOnEsc());
			assertTrue(dialog.isCloseOnOutsideClick());
			window.test(window.find(Button.class).withText("Cancel").single()).click();
			assertFalse(dialog.isOpened());
			assertEquals(1, people.size());

			window.test(buttonAt(window, 1)).click();
			assertTrue(dialog.isOpened());
			window.test(window.find(TextField.class).withLabel("Name").single()).setValue("Grace");
			window.test(window.find(Button.class).withText("Save").single()).click();

			assertEquals(2, people.size());
			assertEquals("Grace", people.get(1).getName());
			assertFalse(dialog.isOpened());

			window.test(treeGrid).select(0);
			window.test(buttonAt(window, 2)).click();
			assertTrue(dialog.isOpened());
			window.test(window.find(TextField.class).withLabel("Name").single()).setValue("Ada Lovelace");
			window.test(window.find(Button.class).withText("Save").single()).click();
			assertEquals("Ada Lovelace", ada.getName());
			assertFalse(dialog.isOpened());

			window.test(treeGrid).select(0);
			window.test(buttonAt(window, 3)).click();
			window.test(window.find(ConfirmDialog.class).single()).confirm();
			assertFalse(people.contains(ada));
		}
	}

