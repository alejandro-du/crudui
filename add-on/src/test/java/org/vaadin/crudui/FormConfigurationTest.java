	private static List<String> labels(Form<?> form) {
		return form.getContent().getChildren().map(HasLabel.class::cast).map(HasLabel::getLabel).toList();
	}

	private static <T extends com.vaadin.flow.component.Component> T field(Form<?> form, String label, Class<T> type) {
		return form.getContent().getChildren().filter(type::isInstance)
				.map(type::cast).filter(component -> label.equals(((HasLabel) component).getLabel()))
				.findFirst().orElseThrow();
	}

	private static Form<ChoiceBean> form(ChoiceBean bean, Field.Builder<?, ?, ?> field) {
		return (Form<ChoiceBean>) AutoGeneratedFormFactory.of(ChoiceBean.class).fields(field).build(bean);
	}

