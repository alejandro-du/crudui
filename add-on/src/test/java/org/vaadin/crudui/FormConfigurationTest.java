	@Test
	void generatedDateConversionsUseSystemZoneAndHandleEmptyValuesForBothBindingStyles() {
		TimeZone previous = TimeZone.getDefault();
		try {
			TimeZone.setDefault(TimeZone.getTimeZone("America/Los_Angeles"));
			ZoneId zone = ZoneId.systemDefault();
			LocalDate initial = LocalDate.of(2024, 3, 10);
			LocalDate edited = LocalDate.of(2024, 11, 3);
			for (String binding : List.of("property", "inferred", "explicit")) {
				DateBean bean = new DateBean();
				bean.setDate(Date.from(initial.atTime(15, 30).atZone(zone).toInstant()));
				var factory = AutoGeneratedFormFactory.of(DateBean.class);
				if (binding.equals("inferred")) {
					factory.fields(Field.of(DateBean::getDate, DateBean::setDate).caption("Date"));
				} else if (binding.equals("explicit")) {
					factory.fields(Field.of(DateBean::getDate, DateBean::setDate, Date.class).caption("Date"));
				}
				Form<DateBean> form = (Form<DateBean>) factory.build(bean);
				DatePicker date = field(form, "Date", DatePicker.class);
				assertEquals(initial, date.getValue());
				assertEquals(Date.from(initial.atTime(15, 30).atZone(zone).toInstant()), bean.getDate());
				date.setValue(edited);
				assertEquals(Date.from(edited.atStartOfDay(zone).toInstant()), bean.getDate());
				date.setValue(initial);
				assertEquals(Date.from(initial.atStartOfDay(zone).toInstant()), bean.getDate());
				date.clear();
				assertNull(bean.getDate());
				date.setValue(edited);
				assertEquals(edited, field((Form<DateBean>) factory.build(bean), "Date", DatePicker.class).getValue());
				DateBean other = new DateBean();
				other.setDate(Date.from(initial.atTime(12, 0).atZone(zone).toInstant()));
				form.setValue(other);
				assertEquals(initial, date.getValue());
				assertEquals(Date.from(initial.atTime(12, 0).atZone(zone).toInstant()), other.getDate());
			}
			TimeZone.setDefault(TimeZone.getTimeZone("Pacific/Apia"));
			DateBean bean = new DateBean();
			Form<DateBean> form = (Form<DateBean>) AutoGeneratedFormFactory.of(DateBean.class).build(bean);
			DatePicker date = field(form, "Date", DatePicker.class);
			date.setValue(LocalDate.of(2011, 12, 30));
			assertFalse(form.isValid());
			assertNull(bean.getDate());
		} finally {
			TimeZone.setDefault(previous);
		}
	}

	@Test
	void explicitDateConvertersTakePrecedenceForBothBindingStyles() {
		Converter<LocalDate, Date> converter = Converter.from(
				date -> Result.ok(date == null ? null : new Date((date.toEpochDay() + 1) * 86_400_000L)),
				date -> date == null ? null : LocalDate.ofEpochDay(date.getTime() / 86_400_000L - 1));
		LocalDate initial = LocalDate.of(2020, 1, 2);
		LocalDate edited = LocalDate.of(2020, 2, 3);
		for (boolean methodReference : List.of(false, true)) {
			DateBean bean = new DateBean();
			bean.setDate(new Date((initial.toEpochDay() + 1) * 86_400_000L));
			var factory = AutoGeneratedFormFactory.of(DateBean.class);
			if (methodReference) {
				factory.fields(Field.of(DateBean::getDate, DateBean::setDate, Date.class)
						.caption("Date").converter(converter));
			} else {
				factory.fields(Field.<DateBean, Date, DateValueField>of("date")
						.caption("Date").converter(converter));
			}
			DatePicker date = field((Form<DateBean>) factory.build(bean), "Date", DatePicker.class);
			assertEquals(initial, date.getValue());
			date.setValue(edited);
			assertEquals(new Date((edited.toEpochDay() + 1) * 86_400_000L), bean.getDate());
		}
	}

	@Test
	void customDateFieldProviderKeepsItsOwnDateValueType() {
		DateBean bean = new DateBean();
		Date initial = new Date(123456789L);
		bean.setDate(initial);
		var factory = AutoGeneratedFormFactory.of(DateBean.class)
				.fields(Field.<DateBean, Date, DateValueField>of("date")
						.fieldProvider(ignored -> new DateValueField()));
		Form<DateBean> form = (Form<DateBean>) factory.build(bean);
		DateValueField field = assertInstanceOf(DateValueField.class, form.getContent().getComponentAt(0));
		assertEquals(initial, field.getValue());
		Date edited = new Date(987654321L);
		field.setValue(edited);
		assertEquals(edited, bean.getDate());
	}

	@Test
	void dateSubclassUsesItsExplicitConverter() {
		Converter<LocalDate, java.sql.Date> converter = Converter.from(
				date -> Result.ok(date == null ? null : java.sql.Date.valueOf(date)),
				date -> date == null ? null : date.toLocalDate());
		SqlDateBean bean = new SqlDateBean();
		bean.setDate(java.sql.Date.valueOf("2020-01-02"));
		var factory = AutoGeneratedFormFactory.of(SqlDateBean.class)
				.fields(Field.of(SqlDateBean::getDate, SqlDateBean::setDate, java.sql.Date.class)
						.caption("Date").converter(converter));
		DatePicker field = field((Form<SqlDateBean>) factory.build(bean), "Date", DatePicker.class);
		assertEquals(LocalDate.of(2020, 1, 2), field.getValue());
		field.setValue(LocalDate.of(2020, 2, 3));
		assertEquals(java.sql.Date.valueOf("2020-02-03"), bean.getDate());
	}

	@Test
	void crudSavesTheDateSelectedInTheGeneratedForm() {
		List<DateBean> saved = new ArrayList<>();
		Crud<DateBean> crud = Crud.of(DateBean.class).onCreate(saved::add).build();
		try (BrowserlessApplicationContext app = BrowserlessApplicationContext.forComponent(() -> crud)) {
			var window = app.newUser().newWindow();
			window.test(window.find(Button.class).atIndex(1)).click();
			window.test(window.find(DatePicker.class).withLabel("Date").single())
					.setValue(LocalDate.of(2024, 6, 10));
			window.test(window.find(Button.class).withText("Save").single()).click();
			assertEquals(1, saved.size());
			assertEquals(Date.from(LocalDate.of(2024, 6, 10).atStartOfDay(ZoneId.systemDefault()).toInstant()),
					saved.get(0).getDate());
		}
	}

