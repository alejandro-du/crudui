	@Test
	void generatedFieldsRoundTripTheirBeanValues() {
		SupportedFieldTypes bean = new SupportedFieldTypes();
		bean.setName("Ada");
		bean.setInteger(12);
		bean.setFloating(3.5);
		bean.setDecimal(new BigDecimal("12.34"));
		bean.setBirthday(LocalDate.of(2000, 1, 2));
		bean.setCreatedAt(LocalDateTime.of(2020, 3, 4, 5, 6));
		Form<SupportedFieldTypes> form = (Form<SupportedFieldTypes>) AutoGeneratedFormFactory
				.of(SupportedFieldTypes.class).build(bean);

		TextField name = field(form, "Name", TextField.class);
		IntegerField integer = field(form, "Integer", IntegerField.class);
		NumberField floating = field(form, "Floating", NumberField.class);
		BigDecimalField decimal = field(form, "Decimal", BigDecimalField.class);
		DatePicker birthday = field(form, "Birthday", DatePicker.class);
		DateTimePicker createdAt = field(form, "Created At", DateTimePicker.class);
		Checkbox active = field(form, "Active", Checkbox.class);
		assertEquals("Ada", name.getValue());
		assertEquals(12, integer.getValue());
		assertEquals(3.5, floating.getValue());
		assertEquals(new BigDecimal("12.34"), decimal.getValue());
		assertEquals(bean.getBirthday(), birthday.getValue());
		assertEquals(bean.getCreatedAt(), createdAt.getValue());
		name.setValue("Grace");
		integer.setValue(42);
		floating.setValue(8.5);
		decimal.setValue(new BigDecimal("99.50"));
		birthday.setValue(LocalDate.of(2001, 2, 3));
		createdAt.setValue(LocalDateTime.of(2021, 4, 5, 6, 7));
		active.setValue(true);
		assertEquals("Grace", bean.getName());
		assertEquals(42, bean.getInteger());
		assertEquals(8.5, bean.getFloating());
		assertEquals(new BigDecimal("99.50"), bean.getDecimal());
		assertEquals(LocalDate.of(2001, 2, 3), bean.getBirthday());
		assertEquals(LocalDateTime.of(2021, 4, 5, 6, 7), bean.getCreatedAt());
		assertTrue(bean.isActive());
	}

